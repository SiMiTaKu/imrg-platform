<p>
  The Men's Rhythmic Gymnastics Internationalization Project ("we") describes below how information
  is handled on the website imrg.work (the "Site") and in IMRG Video Tools, the YouTube tool we
  operate (the "Tool").
</p>

<h3>1. Operator</h3>
<p>Men's Rhythmic Gymnastics Internationalization Project (Representative: Takumi Shimizu)</p>

<h3>2. Information collected on the Site</h3>
<p>
  The Site has no forms for entering personal information such as your name or email address. We do
  not use any advertising tools.
</p>
<p>
  To understand how the Site is used and to improve it, we use Cloudflare Web Analytics, an
  analytics service provided by Cloudflare, Inc. It does not use cookies and does not identify or
  track individual visitors. It collects only information for aggregate statistics, such as the
  pages viewed, referring pages, browser and device type, country or region, and page load times.
  For details, see the
  <a href={LINKS.cloudflarePrivacy} rel="noopener noreferrer" target="_blank"
    >Cloudflare Privacy Policy</a
  >.
</p>
<p>
  Our hosting provider (Amazon Web Services) may process technical records such as IP addresses in
  order to deliver the Site.
</p>

<h3>3. Information accessed by the Tool</h3>
<p>
  The Tool is an internal tool we use to manage our own YouTube channel and is not offered to the
  public. It uses YouTube API Services and, through Google account authorization (OAuth 2.0),
  accesses:
</p>
<ul>
  <li>Basic channel information (channel name, subscriber count, etc.)</li>
  <li>Video uploads, and the titles, descriptions, tags, thumbnails and captions of videos</li>
  <li>Video analytics such as views and audience retention</li>
</ul>

<h3>4. Purpose of use</h3>
<p>
  This information is used only to publish and manage videos on our channel and to analyze them for
  improvement. It is never used for advertising, sold, or shared with third parties.
</p>

<h3>5. Storage</h3>
<p>
  Access tokens are stored only on the operator's own computer and are never sent to external
  servers. Data retrieved from YouTube is stored only to the extent needed for the purposes above.
</p>

<h3>6. Disclosure to third parties</h3>
<p>We do not disclose any information to third parties except as required by law.</p>


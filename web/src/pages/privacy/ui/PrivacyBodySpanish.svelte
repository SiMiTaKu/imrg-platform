<p>
  El Proyecto de Internacionalización de la Gimnasia Rítmica Masculina (en adelante, «el Proyecto»)
  establece a continuación cómo se tratan los datos en el sitio web «imrg.work» (en adelante, «el
  Sitio») y en «IMRG Video Tools», la herramienta para YouTube que gestiona el Proyecto (en
  adelante, «la Herramienta»).
</p>

<h3>1. Responsable</h3>
<p>
  Proyecto de Internacionalización de la Gimnasia Rítmica Masculina (representante: Takumi Shimizu)
</p>

<h3>2. Datos que se recogen en el Sitio</h3>
<p>
  El Sitio no dispone de ningún formulario para introducir datos personales como el nombre o la
  dirección de correo electrónico. Tampoco utilizamos herramientas de publicidad.
</p>
<p>
  Para saber cómo se utiliza el Sitio y poder mejorarlo, empleamos «Cloudflare Web Analytics», el
  servicio de analítica de Cloudflare, Inc. Este servicio no usa cookies y no identifica ni rastrea
  a cada visitante. Solo recoge información agregada, como las páginas vistas, la página de
  procedencia, el tipo de navegador y de dispositivo, el país o la región y el tiempo de carga de
  las páginas. Puedes consultar los detalles en la
  <a href={LINKS.cloudflarePrivacy} rel="noopener noreferrer" target="_blank"
    >política de privacidad de Cloudflare</a
  >.
</p>
<p>
  Además, nuestro proveedor de alojamiento (Amazon Web Services) puede tratar registros técnicos,
  como la dirección IP de origen, con el fin de servir el Sitio.
</p>

<h3>3. Datos a los que accede la Herramienta</h3>
<p>
  La Herramienta es una utilidad interna con la que el Proyecto gestiona su propio canal de YouTube
  y no se ofrece al público. Utiliza los servicios de la API de YouTube y, mediante la autorización
  con una cuenta de Google (OAuth 2.0), accede a los siguientes datos.
</p>
<ul>
  <li>Información básica del canal de YouTube (nombre del canal, número de suscriptores, etc.)</li>
  <li>
    La subida de vídeos y el registro y la actualización de títulos, descripciones, etiquetas,
    miniaturas y subtítulos
  </li>
  <li>Datos analíticos de los vídeos, como las reproducciones y la retención de audiencia</li>
</ul>

<h3>4. Finalidad del tratamiento</h3>
<p>
  Estos datos se utilizan únicamente para publicar y gestionar los vídeos del canal del Proyecto y
  para analizarlos con el fin de mejorar su contenido. No se utilizan con fines publicitarios ni se
  venden o ceden a terceros.
</p>

<h3>5. Conservación y custodia</h3>
<p>
  Los tokens de acceso obtenidos en la autorización se guardan solo en el equipo del responsable y
  no se envían a servidores externos. Los datos obtenidos de YouTube también se conservan solo en la
  medida necesaria para las finalidades indicadas.
</p>

<h3>6. Cesión a terceros</h3>
<p>Salvo obligación legal, no cedemos a terceros ninguno de los datos que recogemos.</p>


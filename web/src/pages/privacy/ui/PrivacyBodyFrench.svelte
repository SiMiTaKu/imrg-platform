<p>
  Le Projet d'internationalisation de la gymnastique rythmique masculine (« nous ») décrit ci-après
  la façon dont les informations sont traitées sur le site imrg.work (le « Site ») et dans IMRG
  Video Tools, l'outil YouTube que nous exploitons (l'« Outil »).
</p>

<h3>1. Exploitant</h3>
<p>
  Projet d'internationalisation de la gymnastique rythmique masculine (représentant : Takumi
  Shimizu)
</p>

<h3>2. Informations recueillies sur le Site</h3>
<p>
  Le Site ne comporte aucun formulaire permettant de saisir des données personnelles telles que
  votre nom ou votre adresse e-mail. Nous n'utilisons aucun outil de diffusion publicitaire.
</p>
<p>
  Afin de comprendre comment le Site est consulté et de l'améliorer, nous utilisons Cloudflare Web
  Analytics, un service de mesure d'audience fourni par Cloudflare, Inc. Ce service n'utilise pas de
  cookies et ne permet ni d'identifier ni de suivre les visiteurs individuellement. Il ne recueille
  que des informations statistiques agrégées : pages consultées, pages de provenance, type de
  navigateur et d'appareil, pays ou région, et temps de chargement des pages. Pour en savoir plus,
  consultez la
  <a href={LINKS.cloudflarePrivacy} rel="noopener noreferrer" target="_blank"
    >politique de confidentialité de Cloudflare</a
  >.
</p>
<p>
  Notre hébergeur (Amazon Web Services) peut traiter des données techniques telles que les adresses
  IP afin d'assurer la diffusion du Site.
</p>

<h3>3. Informations auxquelles l'Outil accède</h3>
<p>
  L'Outil est un outil interne que nous utilisons pour gérer notre propre chaîne YouTube ; il n'est
  pas proposé au public. Il utilise les YouTube API Services et accède, via l'autorisation d'un
  compte Google (OAuth 2.0), aux éléments suivants :
</p>
<ul>
  <li>les informations de base de la chaîne (nom de la chaîne, nombre d'abonnés, etc.) ;</li>
  <li>
    la mise en ligne des vidéos, ainsi que leurs titres, descriptions, mots-clés, miniatures et
    sous-titres ;
  </li>
  <li>les statistiques des vidéos, telles que le nombre de vues et la durée de visionnage.</li>
</ul>

<h3>4. Finalité de l'utilisation</h3>
<p>
  Ces informations servent uniquement à publier et à gérer les vidéos de notre chaîne, et à les
  analyser afin de les améliorer. Elles ne sont jamais utilisées à des fins publicitaires, ni
  vendues, ni communiquées à des tiers.
</p>

<h3>5. Conservation</h3>
<p>
  Les jetons d'accès sont conservés uniquement sur l'ordinateur de l'exploitant et ne sont jamais
  envoyés à des serveurs externes. Les données obtenues auprès de YouTube ne sont conservées que
  dans la mesure nécessaire aux finalités ci-dessus.
</p>

<h3>6. Communication à des tiers</h3>
<p>Nous ne communiquons aucune information à des tiers, sauf lorsque la loi l'exige.</p>


<h3>3. 本工具访问的信息</h3>
<p>
  本工具是本项目用来管理自己 YouTube 频道的内部工具，并不向公众提供。它使用 YouTube API 服务，通过
  Google 账号的授权（OAuth 2.0）访问以下信息。
</p>
<ul>
  <li>YouTube 频道的基本信息（频道名称、订阅人数等）</li>
  <li>上传视频，以及登记和更新视频的标题、简介栏、标签、缩略图和字幕</li>
  <li>视频的播放次数、观看留存率等分析数据</li>
</ul>

<h3>4. 使用目的</h3>
<p>
  上述信息仅用于在本项目的频道上发布和管理视频，以及为改进内容而进行的分析。我们不会将其用于广告目的，也不会向第三方出售或提供。
</p>

<h3>5. 保存与管理</h3>
<p>

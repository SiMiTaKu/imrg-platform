<h3>2. Информация, собираемая на Сайте</h3>
<p>
  На Сайте нет форм для ввода персональных данных — имени, адреса электронной почты и тому
  подобного. Рекламные инструменты мы также не используем.
</p>
<p>
  Чтобы понимать, как читают Сайт, и улучшать его, мы используем сервис аналитики «Cloudflare Web
  Analytics» компании Cloudflare, Inc. Этот сервис не использует файлы cookie и не определяет и не
  отслеживает отдельных посетителей. Он собирает только сводные данные: просмотренные страницы,
  страницы-источники переходов, тип браузера и устройства, страну или регион, время загрузки
  страницы. Подробности — в
  <a href={LINKS.cloudflarePrivacy} rel="noopener noreferrer" target="_blank"
    >политике конфиденциальности Cloudflare</a
  >.
</p>
<p>
  Кроме того, наш хостинг-провайдер (Amazon Web Services) может обрабатывать технические записи,
  например IP-адреса подключений, чтобы доставлять Сайт посетителям.
</p>

<h3>3. Информация, к которой обращается Инструмент</h3>
<p>
  Инструмент — это внутренняя разработка Проекта для управления собственным каналом на YouTube; он
  не предоставляется посторонним лицам. Он использует сервисы YouTube API и через авторизацию в
  аккаунте Google (OAuth 2.0) обращается к следующим данным:
</p>
<ul>
  <li>основные сведения о канале YouTube (название канала, число подписчиков и тому подобное);</li>
  <li>
    загрузка видео, а также добавление и изменение названий, описаний, тегов, обложек и субтитров;
  </li>
  <li>аналитика видео — число просмотров, удержание аудитории и тому подобное.</li>
</ul>

<h3>4. Цели использования</h3>
<p>
  Перечисленные данные используются только для публикации и ведения видео на канале Проекта и для
  анализа, помогающего улучшать содержание видео. Мы не используем их в рекламных целях и не продаём
  и не передаём их третьим лицам.
</p>

<h3>5. Хранение и защита</h3>
<p>
  Токены доступа, полученные при авторизации, хранятся только на устройстве оператора и не
  передаются на внешние серверы. Данные, полученные из YouTube, также хранятся только в объёме,
  необходимом для указанных выше целей.
</p>

<h3>6. Передача третьим лицам</h3>
<p>
  За исключением случаев, предусмотренных законом, мы не передаём полученную информацию третьим
  лицам.
</p>


/**
 * 冊子の番号から、その段だけの番号を取り出す。
 *
 * @remarks
 * 冊子は `3.5.7` のように上の段からの通し番号で書いてあるが、画面では章・節・条が
 * 入れ子の見出しになっていて、どの章のどの節にいるかは開いている場所で分かる。
 * そのため、いちばん下の段の番号だけを出す（`3.5.7` なら `7`）。
 *
 * 付録のように `第1条` と書いてある番号は、区切りが無いのでそのまま返す
 *
 * @param number - 冊子の番号
 * @returns その段だけの番号
 */
export const leafNumber = (number: string): string => number.split('.').at(-1) ?? number

            <h3>3 高体連規則</h3>
            <p>次に示すものを除き、（公財）日本体操協会男子新体操採点規則による。</p>

            <h4>禁止技について</h4>
            <p>団体競技・個人競技ともに下記の技を禁止する。<br>
               なお、禁止技を行なった場合は、その演技を０点とする。<br>
               ※いずれも組運動を含む。<br>
               １　前方宙返り転（１と１／２回転）以上（後ろとびからのひねりを含む）<br>
               ２　後方２回宙返り以上</p>

            <h4>制限技について</h4>
            <p>後方系の跳躍技からひねりをともなって直接正面支持臥の技は、男子採点規則　第２章　第31条の構成条件の中で使用できる回数を１回限りとする。<br>
              上記の回数を超えて使用した場合はその演技の構成点を０点とする。</p>

            <h4>所属マークについて</h4>
            <p>マークは規定どおりとし、ユニフォームと区別がつくようにする。</p>

            <h4>同点順位の決定方法について</h4>
            <p>（１）　団体競技<br>
               　　　①　構成得点の上位チーム<br>
               　　　②　上記の条件が全て同点の場合、主任審判員（構成・実施）の合計得点の上位チーム。<br>
               　　　③　上記の条件が全て同点の場合、主任審判員を除く８名の審判員の合計得点の上位チーム。<br>
               　　　④　上記の条件が全て同点の場合、主催団体に一任。<br>
               （２）　個人競技<br>
               　　　①　２種のうち、最高得点を獲得したもの。<br>
               　　　②　上記の条件が全て同点の場合、２種目の主任審判員の合計点の上位者。<br>
               　　　③　上記の条件が全て同点の場合、主任審判員を除く８名の審判員の合計得点の上位者。<br>
               　　　④　上記の条件が全て同点の場合、主催団体に一任。</p>

            <h4>演技中の停電・選手のゲガの処置について</h4>
            <p>（１）落雷などにより競技場が停電し、伴奏音楽が停止した場合には、審判長の判断により演技を中断してもよい。<br>
               　　　再演技を行わせる。<br>
               （２）演技中、選手が怪我をした場合、監督の判断により演技を中断させてもよい。</p>

            <h4>成績順位および表彰について</h4>
            <p>不慮の事故等で種目の危険があった場合、種目別選手権の表彰対象とする。</p>

        <h2>3 徒手の演技</h2>
        <h4>１　徒手の基礎要素群</h4>
        <p>（１）　各種の徒手・・・上肢、下肢、体前屈、体側屈、体回旋、腕の振動、脚の屈伸、胸の後反、<br>
           　　　　　　　　　　　　体の弾性、波動（蛇動）など様々な複合運動<br>
           （２）　各種の跳躍（ジャンプ）・・・鹿跳び、前後開脚跳び、左右開脚跳びなどさまざまな跳躍。<br>
           （３）　柔軟・・・左右開脚体前屈柔軟、前後開脚柔軟、閉脚体前屈柔軟なさまざまな柔軟。<br>
           （４）　バランス・・・さまざまなバランスなど。<br>
           （５）　倒立・・・さまざまな倒立など。<br>
           （６）　各種の歩走・・・さまざまなステップなど。<br>
           （７）　回転及び転向（ターン・ピヴォット）。<br>
           　以上の要素は、さまざまな方向、さまざまな面、移動を伴うあるいは伴わない、片足支持あるいは両足支持、腕の動きと結びつけるなどの多彩な動きを考慮に入れて実施することができる。</p>

        <h4>構成に要求されるもの</h4>
        <p>演技の構成は、あらゆる徒手の要素を含め、跳躍力、柔軟性、巧緻性などを十分発揮し、あらゆる動きの変化で、その技術は独創的であり、迅速な動きで精神（３秒以上）を含まず、流れるように実施されなければならない。<br>
           その動きのつなぎとして、前転・後転・側転・ブリッジを使用することは認める。</p>

        <h4>実施</h4>
        <p>実施に際しては新体操の特徴を正確に生かしたものでなくてはならない。<br>
           すなわち、正しい身体の位置、スケールの大きさ、支点の制御、移動の正確さなどである。<br>
           身体の動きはすべて、緩急の変化、及び力動感、大きさ、スピードのひつな結びつきをともなった継続的な動作でなくてはならない。<br>
           また、すべての要素は、頭と腕を含む身体全体で行われなくてはならない。<br>
           つまり、動きは局部的であってはならない。</p>


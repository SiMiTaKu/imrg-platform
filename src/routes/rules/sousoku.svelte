        <h4>第50条 手具点検</h4>
        <p>１　競技開始前には手具点検を行う。予備手具も含め、合格した手具のみ競技会に使用することができる。<br>
           ２　合格した手具には組織委員会が準備した合格シールを貼る。<br>
           ３　競技場に入る直前に合格シール点検を行う。<br>
           ４　審判長または当該主任審判から要求があった場合は、演技終了時に再度手具点検が行われることもある。<br>
           ５　手具が検定品であっても劣化等により規格外になった場合は、手具点検によって規格外となることがある。


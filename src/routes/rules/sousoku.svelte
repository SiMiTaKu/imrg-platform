           ４　団体競技では全員が同型、同色の服装で統一のマークをつけて出場しなければならない。<br>
           ５　体操シューズまたは靴下着用で演技しなければならない。色は自由とする。</p>

        <h4>第40条 競技者の権利</h4>
        <p>競技者には以下の権利が保障される
           １　演技は採点規則の規約によって正確で公平に採点される。<br>
           ２　本会場での公式練習と綿密に準備された演技場での演技が実施できる。<br>
           ３　演技終了後、得点が速やかに表示される。または当該競技会の競技規則に応じた公開がされる。<br>
           ４　演技の中断が競技者に原因がない場合や裁定審判部に認められた不可抗力の事については、演技全体のやり直しができる。<br>
           ５　競技会でのすべての得点は、主催者より公式演技結果として受け取ることができる。</p>

        <h4>第41条 競技者の規律</h4>
        <p>競技者は以下の規則を厳守しなければならない。<br>
           １　競技者と審判は、お互いに信頼と尊重をしなければならない。<br>
           ２　競技規則及び採点規則を熟知し、それに従って競技者としてふさわしい行動をしなければならない。<br>
           ３　採点規則に基づいた採点結果を受け入れなければならない。<br>
           ４　マイクロホンまたは主任審判員の呼び出しを受けた後でなければ演技面に入ることはできない。また、呼び出し後は速やかに入場しなければならない。<br>
           ５　演技終了後、競技者は速やかに演技面より退場しなければならない。<br>
           ６　競技場で指定された場所以外でのウォーミングアップをしてはならない。<br>
           ７　競技者は演技中、審判員に話しかけてはならない。<br>
           ８　規律なく乱暴な言動をとったり、他の競技者の妨害をしてはならない。<br>
           ９　競技者は演技中に故意に号令などの合図をしたり、話したりしてはいけない。<br>
           10　競技者は演技中に試合を放棄する態度をとってはいけない。<br>
           11　競技エリア内において、観衆に対して不快な言動をとってはならない。</p>

    <h2>7 監督者・コーチ</h2>
        <h4>第42条 監督者・コーチの責務と規律</h4>
        <p>監督者およびコーチは競技会が円滑に開催できるために、マナーやモラルを守るとともに、以下の規則を厳守しなければならない。<br>
           １　監督者は所属選手に対しすべての責任を負い、競技が円滑に進行するための指示を与えなければならない。<br>
           ２　監督者は競技開始前に開催される監督会議に出席しなければならない。<br>
           ３　監督者は監督会議の内容を所属選手および関係者への連絡を報告する責任がある。<br>
           ４　競技会が円滑に開催できるために大会競技規則を厳守しなければならない。<br>
           ５　監督者は演技面に位置できない。<br>
           ６　監督者は緊急時を除き、演技中の競技者に干渉してはならない。<br>
           ７　監督者は演技城内において、観衆や競技役員に対して不愉快な行動をとってはならない。<br>
           ８　採点結果についての疑問点について審判長に問い合わせはできるが、審判員個人へ直接の抗議はしてはならない。</p>

        <h4>第43条 規律違反</h4>
        <p>競技者および監督・コーチに規律違反があった場合は、採点規則によって原点または処分をされることがある。</p>

    <h2>8 一般的な競技規則</h2>
        <h4>第44条 新体操の演技</h4>
        <p>新体操の演技は、徒手系要素と回転系要素を織り交ぜ、団体競技では６人の同調性と力強さを、個人競技では４種類の手具の特性に合わせた操作を、体を極限まで運動させながら表現する種目である。各競技に求められた要素を全て含み、高い技術的価値と各種要素の多様性音楽と動きの関係や独創性を持ち、すべての運動が合理性と安定性を持って実施されなければならない。</p>

        <h4>第45条 伴奏音楽</h4>
        <p>１　すべての競技において伴奏音楽をつけなければならない。<br>
           ２　伴奏音楽はよりよい音色とメロディーによって、特徴付けられるものでなければならない。すなわち演技の性格に合致し、途切れずはっきりとしたリズムを持ち、競技者の動きのリズムと調和していなければならない。<br>
           ３　伴奏音楽は楽器（シンセサイザーを含む）で演奏されたもの、または人の声に限る。<br>
           ４　伴奏音楽は、音楽を記録した記録媒体等を使用する。大会要項で別途指定された場合はそれに準じる。<br>
           ５　演技面の入退場には伴奏音楽をつけてはならない。<br>
           ６　組織者側に責任のない理由で伴奏音楽が中断された場合は、原則として演技の復行はできない。</p>

        <h4>第46条 得点</h4>
        <p>１　自由演技は構成（Ｄ）と実施（Ｅ）のそれぞれ10点満点の計20点満点で採点される。また規定演技は実施（Ｅ）の10点満点で採点される。<br>
          ２　主任審判員を除いた４名の審判員の最高点及び最低点を除外し、有効点の平均点を小数点第３位までとし、第４位は切り捨て得点とする。主任審判員が適用する原点があった場合は、その得点から減点し最終得点とする。</p>

        <h4>第47条 演技時間</h4>
        <p>すべての演技は演技時間が下記のとおりに定められる。団体演技ではチームのうち１人以上の動き始めからチーム全員が完全に動きを止めるまでの時間とし、個人競技では競技者の動き始めから完全に動きを止めるまでとする。<br>
          ・団体競技　２分45秒から３分00秒
          ・個人競技　１分15秒から１分30秒</p>

        <h4>第48条 演技人数10</h4>
        <p>団体競技の演技人数は６名で行うものとする。ただし５名または４名でも競技に参加することができるが減点される。（採点規則第26条参照）</p>


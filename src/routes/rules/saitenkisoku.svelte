               　（３）　難度要素の安定<br>
               　　　　　難度要素は競技者の能力に応じて構成されなければらない。<br>
               ４　手具操作の技術的価値<br>
               　（１）　手具操作における左手と右手の均衡<br>
               　　　　　手具の操作は、１つの調和のとれた構成として、片寄ることなく、左手と右手で操作されなければならない。<br>
               　（２）　投げ受けの技術的価値<br>
               　　　　　手具の投げ受けは、手具操作の流れを止めることなく行われなければならない。<br>
               　　　　　また、手だけでなく、その他の部位を使った投げ受けやし野外での投げ受けも高い技術的価値として認めることができる。</p>

            <h4>第57条 多様性の採点</h4>
            <p>１　徒手系要素の多様性<br>
               　　様々な徒手系の運動要素と組み合わせにおいて、多様性に富むものでなければならない。<br>
               ２　転回系要素の多様性<br>
               　　様々な転回系要素や種類、その組み合わせにおいて、多様性に富むものでなければならない。<br>
               ３　手具操作の多様性<br>
               　　様々な手具の操作やその組み合わせにおいて、多様性に富むものでなければならない。<br>
               　　（付録：各手具の演技参照）<br>
               ４　空間仕様の多様性<br>
               　　様々な移動を含め、その方向、大きさ、起動、高さにおいて、演技面全体を使うものでなければならない。<br>
               ５　リズムの変化の多様性<br>
               　　音楽の性格、そのリズムと完全に一致した運動で、そのリズムの変化が多様性に富むものでなければならない。<br>
               ６　ダイナミズム（力動感）の変化と多様性<br>
               　　ダイナミズムとはスピードと力強さの変化によって表現される力動感のことで、その緩急の変化において、多様性に富むものでなければならない。</p>

            <h4>第58条 音楽と動きの関係の採点</h4>
            <p>新体操の伴奏音楽は、よい音色とメロディーによって特徴付けられるものでなければならない。<br>
               演技は音楽の性格やリズムに合致しなければならない。</p>

            <h4>第59条 ボーナス加点</h4>
                １　独創性<br>
                　　構成は、新しい技術や新しい組み合わせなど、新しさの探求と技術的な創造性によって特徴付けられる独創性が求められる。<br>
                　　その独創性が認められる構成にはボーナス加点が与えられる。<br>
                　　（１）　独創的な構成とは、以下の事柄などが求められる。<br>
                　　　　　①　新しい要素（身体の動きの要素、手具操作の要素、転回系またはそれらの連携の要素）<br>
                　　　　　②　競技者と手具の関係における新しさ<br>
                　　　　　③　すでにある要素の新しい実施方法<br>
                　　　　　④　すでにある要素の新しい組み合わせ<br>
                　　　　　【加点・・・0.20点】<br>
                ２　追加の難度<br>
                　　演技の技術的な価値は主として難度のレベルと数、その組み合わせ価値によって考慮される。<br>
                　　以下の（１）〜（４）の場合に、その「技術の価値」に対しボーナス加点が与えられる。<br>
                　　（１）　構成中に４つ以上のＤ難度が入っている場合<br>
                　　（２）　手具を投げ上げている間に、４つ以上の徒手系や転回系を組み合わせて実施するもの、またはＤ難度の投げ受けを２本投げで行なった場合。<br>
                　　（３）　手具を保持して行うＤ難度の転回系に、投げまたは２回以上の操作を実施するものが入っていた場合<br>
                　　（４）　視野外の投げ上げや受け取り、手以外での投げ上げや受け取りが入っていた場合。<br>
                　　【加点：項目一つにつき・・・0.10点】</p>


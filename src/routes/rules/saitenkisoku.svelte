               　　　　ウ　高い難度を低い難度で読み替えても、すべての難度が３名未満の場合は、難度として認めない。</p>

        <h3>4 個人競技における難度</h3>
            <h4>第69条 転回系における手具操作と難度</h4>
            <p>演技の中で転回系を実施した場合の難度は、基礎難度表によって価値が決められる。<br>
               ただし、以下の条件に当てはまる場合は、その難度から１ランクアップされる。<br>
               １　手具の投げ受けの間に転回系を実施した場合は、その転回系の難度から１ランクアップされる。<br>
               ２　２回以上の手具操作をともなって、実施した場合。<br>
               　（１）　スティック<br>
               　　　　①　端または中央部などを持って２回以上回す。<br>
               　　　　②　左右の手を持ち替えて１回以上回す。<br>
               　（２）　リング<br>
               　　　　①　１つのリングまたは２つのリングを２回以上回す。<br>
               　　　　②　２つのリングを１回転づつ順番に回す。<br>
               　　　　③　１つのリングを左右の手を持ち替えて１回以上回す。<br>
               　（３）　ロープ<br>
               　　　　①　片手または両手で、１本、２つ折り、３つ折り、４つ折りなどにして２回転以上回す。<br>
               　　　　②　左右の手を持ち替えて、１回以上回す。<br>
               　（４）　クラブ<br>
               　　　　①　頭、または首を持って２回以上回す。<br>
               　　　　②　２本のクラブを１回転ずつ順番に回す。<br>
               　　　　③　１つのクラブを左右の手を持ち替えて、１回以上回す。<br>
               ３　その他の手具操作<br>
               　（１）　転回系を実施している間に手具を床に打ちつけてとる。<br>
               　（２）　転回系を実施している間に手具を転がして、着地と同時にとる。 </p>

            <h4>第70条 投げ受けの難度</h4>
            <p>演技の中で投げ受けを実施した場合、その間に実施した徒手系（※）または転回系の数によって以下のように難度が決められる。<br>
               ただし、転回系が含まれていた場合は第69条の１の条件と比較して、高い方の難度を採用する。<br>
               　※ここでの徒手系は、縦軸または横軸で、360°回転したもののみを１つとして数える。<br>

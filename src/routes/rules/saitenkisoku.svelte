               　（２）　右投げ右受け１回<br>
               　（３）　（１）（２）を含む３回以上の投げ上げ<br>
               　（４）　１m以上のころがし<br>
               　（５）　プロペラ回旋２回<br>
               【要素が不足した場合　減点：１つにつき・・・0.30点】<br>

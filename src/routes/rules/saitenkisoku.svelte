        <h3>3 実施（Ｅ）</h3>
            <h4>第61条 演技のできばえ</h4>
            <p>演技は手具操作をともなった徒手系の技術、転回系の技術、伴奏音楽との調和など全体の調和と安定性があり、全体を通じて途切れない印象でのびのびと行われなければならない。<br>
               伴奏音楽に合わせ、軽快で美しく、かつ優美な表現を持った実施が求められる。</p>

            <h4>第62条 手具操作の技術の採点</h4>
            <p>１　一般的な技術<br>
               　　演技中の手具は、常に自然性を持ち、その手具自体の重さからくる惰力を利用して、動かなければならない。<br>
               　　また演技上必要とされる静止を除いて、手具を止めてはならない。<br>
               ２　振り回しの技術<br>
               　　手具を手に持って、振ったり回したりする場合は、原則として腕の延長のように扱わなければならない。<br>
               ３　投げ受けの技術<br>
               　（１）　手で手具を投げる技術<br>
               　　　　　特殊な投げを除き、原則として振りや回しの技術を利用して投げなければならない。<br>
               　（２）　手具を受ける技術<br>
               　　　　　手具の受け取りは、手具の落下に合わせ、その次の操作に必要そされる部分を、自然性を持って受け取り、止めることなく次の操作に移らなければならない。</p>

            <h4>第63条 体の動きの技術の採点</h4>
            <p>身体の動きの技術は、次の項目で採点される。<br>
               １　徒手系の技術<br>
               　　徒手系は、美しい姿勢と柔軟性をもって行われ、みぞおちから始まる動きの自然性や深さ、大きさ、動きの間やアクセント、跳躍の高さ、そしてスピードに変化があり、身体の四肢の部分まで制御された動きでなければならない。<br>
               ２　転回系の技術<br>
               　　転回系は、スピードと高さ、回転軸の正確性と着地の安定性をもってダイナミックな動きでなければならない。<br>
               ３　リズミカルな実施<br>
               　　伴奏音楽に合わせ、軽快に伸びやかに行わなければならない。</p>

            <h4>第64条 ボーナス加点</h4>
            <p>熟練度と芸術性<br>
               　熟練度とは、手具を扱う技術と身体の動きの技術とが、完璧にかつ同時にコントロールされていることをいう。<br>
               　また芸術性とは、それらの技術を用いて、音楽のテーマと構成のメッセージを観衆に表現し伝え感動させることを言う。<br>
               　以下を満たした場合、これに対してボーナス加点が与えられる。<br>
               　（１）　演技全体が欠点なく演じられた場合。※<br>
               　（２）　演技全体を通じて、完璧な技術、ゆとり、卓抜な大きさを持って行われた場合。<br>
               　（３）　音楽のテーマと構成のメッセージを完璧に表現し演じられた場合。<br>
               　【加点・・・各0.10点】<br>
               　　※　ここでの欠点は第65条実施の欠点表に記載されている「徒手の動きの技術」以外の欠点がない場合をいう。</p>


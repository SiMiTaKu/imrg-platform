    <h1>第2章 採点規則</h1>

    <h2>1 総則</h2>
        <h4>第１条 採点規則の役割</h4>
        <p>１　採点規則は、国際および国内競技における競技を共通の基準をもって判定し、その評価を客観的にならしめるものである。<br>
           ２　審判員の能力と採点の技術を高め、また競技者や指導者に競技のための練習の指針として役立たせるものである。<br>
           ３　審判員は、本規則を厳守しなければならない。厳守しない審判員は審判長によって改心されることがある。</p>

    <h2>2 審判</h2>
        <h4>第２条 競技と審判</h4>
        <p>１　新体操は判定競技であるから、審判員によって方向性と指導性とが決まるので、その責任は極めて重大である。<br>
           ２　審判員は、広い視野と高い見識と深い経験とを有し、かつ人格において良心的、公平でなければならない。<br>
           ３　審判員は、その特別の権限と職務上の立場から、その面前で実施した演技を深く感得し、正しく判定できなければならない。<br>
           ４　審判員は、演技の出来ばえ、構成における運動の難度および価値、その音楽伴奏との調和など、すべてを観察理解する能力が必要である。<br>
           ５　審判員は、技術の進歩以外に調和のある柔軟性および男子としての力強さを判定することも必要である。<br>
           ６　審判員は、観衆の拍手や見世物で価値のない演技に影響を受けることなく信念に基づく判定が必要である。<br>
           ７　不正または誤った判定は、指導者および競技者に大きな影響を与えるばかりでなく、新体操の普及にも支障をきたす。</p>

        <h4>第３条 審判員規定</h4>
        <p>１　本協会の監督下に開催される競技会では、公認審判認定規定に基づき資格を有した審判員が審判業務を行う。<br>
           ２　審判長・審判員は職責に専任し、いかなる名目を持っても、チームを指導し、競技に参加し、または他の任務を受諾することはできない。<br>
           ３　審判員は任命された競技会の全期間を通じ競技場でその任務を全うしなければならない。<br>
           ４　審判員は、いかなる場合にも採点について影響を受けてはならない。<br>
           ５　審判員は、競技会前に審判会議と審判研修会に出席する義務があり、これに出席しないと服務できない。<br>
           ６　すべての審判員において各自の採点に対しての責任は全面的に自分自身にある。<br>
           ７　審判員は常に専門家としてのマナーを守り、偏見のない、倫理的に正しい模範的な態度で行動しなければならない。<br>
           ８　審判長ならびに審判員は競技開始１時間前に競技場に集合し、競技の移行順序・臨時の変更などについて通知を受ける。<br>
           ９　審判員は、定められた服装を着用し業務を行う。<br>
           　（１）　グレーのズボン<br>
           　（２）　ネイビーブルーの上衣<br>
           　（３）　白のＹシャツ　<br>
           　（４）　ネクタイ　<br>
           　（５）　審判バッヂ</p>

        <h4>第４条 審判研修会と審判会議</h4>
        <p>１　審判会議および審判研修会では、規定演技のついては公式解説文または公式映像を参考にし、自由演技については、演技の構成・実施の良否を十分に審議し、採点の焦点を明らかにしなければならない。<br>
           ２　審判会議で能力不十分と認められた審判員は競技会から除名されることがある。</p>

        <h4>第５条 審判員宣誓</h4>
        <p>審判員は、次の宣誓文を厳粛に宣誓する。<br>
           『私は、審判員の資格において、スポーツの品位および誠実の精神を持ってのみ行動すること。ならびに、人物・所属を念頭に置かず、実施された演技を良心的に審判することを誓います。』</p>

        <h4>第６条 審判団の構成</h4>
        <p>１　競技会の審判団は原則として男子で編成する。<br>
           ２　審判団は原則として上級審判員、審判長、それぞれの種目において構成と実施に分かれ、主任審判員１名と審判員４名ずつ、ならびに線審２名、計時審１名と補審で構成される。<br>
           ３　予選競技と決勝競技か行われる競技会では、種目ならびに構成と実施を入れ替えて審判する。</p>

        <h4>第７条 上級審判員</h4>
        <p>上級審判員は上級審判部内規に基づき以下の職務にあたる。<br>
           １　競技を監督する事と反則や競技執行に影響を及ぼす特別な状況に対処する事。<br>
           ２　審判員一人または数名による重大な審判エラーがある場合、必要な処置を取る事。<br>
           ３　継続して審判員が授与する点数を再審して業務が不十分または不公平と思われる審判員に対して警告を発する事。<br>
           ４　警告の不満足な結果の後、審判人員を排除して交賛する事。</p>

        <h4>第８条 審判長</h4>
        <p>１　審判長は男子新体操委員会で任命する。<br>
           ２　審判長は、定めた日時・場所に審判部を招集し、競技会の採点および成績作成の順調な進行のために必要なあらゆる決定を行う。<br>
           ３　審判会議で能力不十分と認める審判員を競技会から除名することができる。<br>
           ４　審判長は、競技会のあらゆる機会に審判員に干渉できる。正しく、かつ満足すべき方法で行動しない審判員に対しては、主任審判員の意見を聞いた上で、これを除名し交代させることができる。</p>

        <h4>第９条 主任審判員</h4>
        <p>１　主任審判は、主任を務めるすべての演技を採点する。ただし主任審判員の採点は採点計算には加えられない。<br>
           ２　主任審判は、各審判員が提出した採点を注意して点検し、規則に反する採点が行われた場合、または点数に乱れがあった時には、主任審判の得点を示して協議する。<br>
           ３　主任審判員は最初の競技者終了後、必要があれば各審判員を招集して協議し、共通の出発点を求める。<br>
           ４　主任審判は、裁定審判部の決議に参与する。<br>
           ５　主任審判員が適用する減点があった場合は、これを有効点の平均から減点し最終得点を決定する。</p>

        <h4>第10条 構成（Ｄ・Ａ）審判</h4>
        <p>構成審判は実施された演技の構成的価値を判断し10点満点で採点する。</p>

        <h4>第11条 実施（Ｅ）審判</h4>
        <p>実施審判は実施された演技の出来栄えを判断し10点満点で採点する。</p>

        <h4>第12条 線審</h4>
        <p>線審は、演技面のコーナーに位置し、競技者の身体または手具の場外違反の有無を判定する。<br>
           違反の都度、赤旗で合図し演技後に実施主任審判員に回数および減点を報告する。</p>

        <h4>第13条 計時審</h4>
        <p>計時審は以下の時間を計時し、構成主任審判員に報告する。<br>
           １　入場から演技開始までの時間<br>
           ２　演技開始から演技終了までの時間</p>

        <h4>第14条 補審</h4>
        <p>補審は審判業務の補助を務める。また緊急の場合は審判交代に応じる。</p>

    <h4>【上級審判部】内規</h4>
    <p>審判部長、ＦＩＧ技術委員（ＪＧＡ選出）が上級審判部を構成する。但し、必要に応じて審判部が指定するエキスパート１名（審判部員メンバー、または熟練審判員）を選出することができる。（合計２〜３名）<br>
       上級審判部長は部員の互選のより定める<br>
       上級審判部の職務は：<br>
       　１．　競技を監督する事と反則や競技執行に影響を及ぼす特別な状況に対処する事。<br>
       　２．　審判員一人または数名による重大な審判エラーがある場合、必要な処置をとる事。<br>
       　３．　継続して審判員が授与する点数を最新して業務が不十分または不公平と思われる審判員に対して警告を発する事。<br>
       　４．　警告の不満足な結果の後、審判人員を排除して交賛する事。</p>

    <h4>【裁定審判部】内規</h4>
    <p>最低審判部は、理事会メンバー２名（うち一人は部長を務める）と審判部メンバー１名（採点業務に関与していないも者）または審判部が指名したエキスパート審判員で構成される。（合計３名）<br>
      理事会のメンバーは理事会が指名し、審判部メンバーは関連審判部が指名する。<br>
      裁定審判部の職務は：<br>
      　１．　最低審判部は競技終了後適切な時に上級審判部によって警告されたり外された審判員からの嘆願を取り扱う。<br>
      　２．　最低審判部は定款・競技規則、ルールとガイドラインの条件が守られているかも監視する。<br>
      　　　　反則の場合には、最低審判部は処分に責任がある機関に報告する。</p>


    <h2>3 一般的な採点規則</h2>
        <h4>第15条 採点方法と採点の開き</h4>
        <p>１　審判員は０点から10点までの各１点を20等分した点数で採点する。<br>
          ２　主任審判員と４名の審判の場合<br>
          　　構成・実施それぞれに主任審判員を除いた５名の審判員の最高点および最低点を除外し、有効点の平均（小数第４位以下を切り捨て）を求め合計する。主任審判員が適用する原点があった場合は、その平均点の合計から減点する。<br>
          ３　主任審判員が１審を兼ねる場合<br>
          　　構成実施それぞれに主任審判員を含めた４名の審判員の最高点および最低点を除外し、有効点の平均（少数第４位以下を切り捨て）を求め合計する。主任審判員が適用する減点があった場合は、その平均点の合計から原点する。<br>
          ４　有効点の開きは以下の点数より大きくてはならない。<br>

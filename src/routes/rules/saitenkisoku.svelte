          ５　全審判員の採点最高点と最低点の開きは以下の点数より大きくてはならない。<br>
          <img src="../../../static/image/rules/tennsuu.png" alt="全審判員の点数の開き" width="400px">
          <br>
        </p>


        <h4>第16条 基準点</h4>
        <p>基準点は、全審判員と主任審判員が集合して話し合っても問題が解決されない場合に適用される。計算は次のように行う。<br>（有効点の平均＋主任審判員の採点）／２＝基準点</p>

        <h4>第17条 演技時間</h4>
        <p>１　競技規則47条の時間に違反した場合は、長すぎても短すぎても原点とする。<br>
           　　【構成主任審判より原点：１秒につき・・・0.005点】<br>
           ２　演技時間が下記に満たなかった場合は得点を次の通りにする。<br>
           　　団体競技　２分３０秒　　　個人競技　１分００秒<br>
           　　【得点：構成・実施とも0．00点】</p>

        <h4>第18条 演技開始までの時間</h4>
        <p>入場から演技開始までの時間が次の時間を超えた場合は減点とする。<br>
           　団体競技・・・３０秒　　　個人競技・・・２０秒<br>
           　【実施主任審判より減点・・・0．20点】

        <h4>第19条 演技面への入退場</h4>
        <p>演技面への入退場は、徒歩または駆け足で速やかに行わなければならない。<br>
           　【違反した場合　実施審判より減点・・・0．20点】</p>

        <h4>第20条 場外</h4>
        <p>場外の扱いは以下のとおりとし、実施主任審判より減点する。<br>
           　　＊５、６の各種具とは２つ組の手具のそれぞれを指す。<br>
           １　体の一部や手具が競技面を超えて床に触れた場合を場外とする。<br>
           　　空中でラインを超えても減点の対象とはならない。<br>
           ２　保持された手具がラインオーバーした場合は、身体の一部として扱い減点する。<br>
           ３　片足、両足または身体の一部がラインオーバーをした場合。<br>
           　　【減点：１回につき・・・0．10点】<br>
           ４　団体競技について、何人かの競技者が同時にラインオーバーをした場合。<br>
           　　【減点：１名につき・・・0．10点】<br>
           ５　手具が身体から離れてラインオーバーした場合。<br>
           　　【減点：１名につき・・・0．10点】<br>
           ６　１回の過失により身体や手具が、繰り返しラインオーバーをした場合。<br>
           　　【減点：身体または各手具１回につき・・・0．10点】</p>

        <h4>第21条 試合着</h4>
        <p>試合着に関する違反は以下のとおり減点する。<br>
           １　競技規則39条に違反した場合（含所属マーク）ただし、プリント柄の若干の違いは減点しない。<br>
           　　【構成主任審判より減点：１名につき・・・0.20点】<br>
           ２　破れた服装で演技した場合。ただし演技中に敗れたものは減点しない。<br>
           　　【実施審判より減点：１名につき・・・0．10点】<br>
           ３　著しく服装が乱れた場合。<br>
           　　【実施審判より減点：１名につき・・・0．10点】</p>

        <h4>第22条 伴奏音楽</h4>
        <p>　競技規則第45条に基づき、１から４の減点をする。<br>
           １　伴奏音楽がなかった場合。<br>
           　　【構成主任審判より減点：0．50点】<br>
           ２　入退場に伴奏音楽をつけた場合。<br>
           　　【構成主任審判員より減点：0．20点】<br>
           ３　音楽に３秒以上の停止があった場合<br>
           　　【構成審判より減点：0．20点】<br>
           ４　組織者側に責任のない理由で音楽が中断された場合は、原則として復興できない。<br>
           　　中断があった場合、審判長と競技部長は原因を速やかに確認し処理に当たる。</p>

        <h4>第23条 手具</h4>
        <p>１　演技途中で手具が破損した場合、競技者は手部の差し替えをしなければならない。<br>
           ２　手具の差し替えのための場外は減点の対象とならない。<br>
           ３　際変えのための中断は、演技の中断として減点する。<br>
           　　【実施審判より減点：１秒につき・・・0．10点】<br>
           ４　破損した後、手具の差し替えを行わなかった場合は、破損後の演技の価値はないものとして採点する。<br>
           ５　手具が演技終了時に破損した場合は、手具に触れずに終了したものとして扱う。<br>
           ６　演技中の手具が破損した場合その演技をやり直すことはできない。<br>
           ７　規格外の手具の使用。<br>
           　　【得点：構成・実施とも0.00点】<br>
           ８　予備手具を使用した場合<br>
           　　【構成主任審判員より減点・・・0.50点】</p>

        <h4>第24条 規律</h4>
        <p>１　競技者が競技規則第41条に違反した場合<br>
           　　【実施審判より減点：0．20点】<br>
           ２　監督者が競技規則第42条に違反した場合は厳重に注意をした上で減点や処分を決める。<br>
           　　【実施主任審判員より減点・・・0．20点】<br>


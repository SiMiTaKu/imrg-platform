        <h3>3 団体競技における難度の組み合わせ</h3>
            <h4>第68条 交差技と組運動の難度</h4>
            <p>１　交差技<br>
               　　交差技の難度は以下の通りとする。<br>
               　（１）　徒手系の上を転回系で跳び越えた場合は転回系の種目の難度を採用する。<br>
               　（２）　転回系の交差技は、転回系の途中を飛び越えていなければならない。<br>
               　　　　　最低条件として、転回系の着地寸前に跳び越えることとする。<br>
               　　　　①　転回系の交差技は、転回系の途中を跳び越えていなければならない。<br>
               　　　　②　着地後に跳び越えた場合は（１）の扱いとする。<br>
               　　　　③　２段の交差技の難度<br>

               <img src="../../../static/image/rules/AMCdifficulties.png" alt="転回系の組合せ難度表" width="40%"><br>

               　　　　④３段以上の交差技をすべてＢ難度以上の展開系で実施した場合はＤ難度とする。Ａ難度が入っていた場合は、この扱いにはならない。</p>
            <p>２　組・組立運動<br>
               　　組・組立運動の難度は以下のとおりとする。<br>
               　（１）　組み・組立運動の難度表<br>

               <img src="../../../static/image/rules/liftdifficulties.png" alt="組・組立運動の難度表" width="55%"><br>

               　　　　※１　次に展開系に続けた場合に難度として扱う。<br>
               　　　　※２　Ｃ難度以上の転回系の場合は、その転回系の難度とする。<br>
               　（２）　組・組立運動での難度の格上げ<br>
               　　　　①　肩上倒立をとばし技で超えた場合は、跳躍系は１ランク、宙返り系は２ランク難度が上がる。<br>
               　　　　②　組倒立で片手倒立または支持者が伸腕で支持した場合は、１ランク難度が上がる。<br>
               ３　シリーズの難度の判定<br>
               　　競技者が、いくつかのグループに分かれ、次々と転回系を行なった場合、難度の判定は以下のとおりとする。<br>
               　（１）　原則として交差技と組・組立運動を除き、３名以上が実施した難度を採用する。<br>
               　　　　　ただし高い難度の技を低い難度として読み替えることはできる。<br>
               　（２）　いくつかのグループに分かれて同じ難度の転回系を実施した場合<br>
               　　　　①　３・３に分かれた場合<br>
               　　　　　ア　原則として、高い難度を実施したグループの難度を採用する。<br>

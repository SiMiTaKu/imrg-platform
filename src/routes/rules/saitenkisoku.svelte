            <h4>第53条 手具の要素と難度</h4>
            <p>１　投げ上げ<br>
               　（１）　手具の投げ上げの高さは、競技者が投げたところから最低２m以上とする。<br>
               　　　　　低い場合は投げ上げとして扱わない。<br>
               　（２）　スティックの投げ受けの要素は、受け損じた場合には要素として扱わない。<br>
               　（３）　手具を投げている間に、徒手系や転回系を行い受け損じた場合、投げ上げの要素として数えるが、投げ受けの難度としては扱わない。<br>
               　　　　　ただし、リングやクラブの２つの同時投げで片方の手具のみ受け損じた場合は、投げ上げの難度として数える。<br>
               　（４）　２つ同時投げは、片手、両手または足で投げるものとし、受けは自由とする。<br>
               　　　　　ただし、２つのリングを結合して投げた場合や、片方の手具が投げたところから２mに満たない場合は要素として認めない。<br>
               ２　ころがし<br>
               　　ころがしが短かった場合は、要素としては扱わない。<br>
               ３　ロープの様々な跳び<br>
               　　前回し跳び、後ろ回し跳びが２回連続でなかった場合、移動をともなう跳びの距離が短かった場合は要素としては扱わない。</p>


               　　　　②　４・２または５・１に分かれた場合<br>
               　　　　　ア　原則として、人数の多いグループの難度を採用する。<br>
               　　　　　イ　異なる種目であっても、６名が実施すれば難度が上がる種目の組み合わせの場合はランクアップされる。<br>
               　　　　　ウ　人数の少ないグループが、交差技または組・組立運動の場合は難度として採用し、難度の高いグループを採用する。<br>
